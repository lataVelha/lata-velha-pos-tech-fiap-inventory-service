-- DOMAIN (Inventory)

CREATE TABLE PECA (
    ID        BIGSERIAL     PRIMARY KEY,
    NOME      VARCHAR(150)  NOT NULL,
    DESCRICAO TEXT,
    VALOR     NUMERIC(10,2) NOT NULL,
    ATIVO     BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE PECA_ESTOQUE (
    PECA_ID               BIGINT  PRIMARY KEY,
    QUANTIDADE_ARMAZENADA INTEGER NOT NULL,
    QUANTIDADE_DISPONIVEL INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT FK_PECA_ESTOQUE FOREIGN KEY (PECA_ID) REFERENCES PECA(ID)
);

-- EXECUCAO_SERVICO_ID é apenas uma referência de aplicação (não há FK: EXECUCAO_SERVICO
-- vive no banco do OsService). PECA_ID continua FK local, PECA existe neste banco.
CREATE TABLE PECA_ALOCADA (
    ID                  BIGSERIAL     PRIMARY KEY,
    EXECUCAO_SERVICO_ID BIGINT        NOT NULL,
    PECA_ID             BIGINT        NOT NULL,
    STATUS              VARCHAR(30)   NOT NULL,
    ATUALIZADO_EM       TIMESTAMP,
    QTD_SOLICITADA      INTEGER       NOT NULL,
    QTD_RESERVADA       INTEGER       NOT NULL DEFAULT 0,
    QTD_ENCOMENDADA     INTEGER       NOT NULL DEFAULT 0,
    VALOR_UNITARIO      NUMERIC(10,2) NOT NULL DEFAULT 0,
    QTD_INSTALADA       INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT FK_PECA_ALOCADA_PECA FOREIGN KEY (PECA_ID) REFERENCES PECA(ID),
    CONSTRAINT UK_PECA_ALOCADA      UNIQUE (EXECUCAO_SERVICO_ID, PECA_ID)
);
